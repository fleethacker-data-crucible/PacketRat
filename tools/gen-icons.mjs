// Generates Web/icons.js from Lucide's SVG sources, so PacketRat ships only the icons it uses and
// never loads anything from a CDN (docs/UNIFIED-UI.md section 6). Development-only; the output is
// committed and the target workstation needs no Node.js.
//   npm pack lucide-static@1.54.0 && tar -xzf lucide-static-1.54.0.tgz
//   node tools/gen-icons.mjs package/icons
// Re-run only when the icon list changes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LUCIDE_VERSION = '1.54.0';
// PacketRat's icon name -> Lucide icon name.
const ICONS = {
  overview: 'layout-dashboard',
  queue: 'list-checks',
  intelligence: 'sparkles',
  dismissed: 'ban',
  settings: 'settings',
  power: 'power',
  keyboard: 'keyboard',
  themeSystem: 'sun-moon',
  themeLight: 'sun',
  themeDark: 'moon',
  collapse: 'panel-left-close',
  expand: 'panel-left-open',
  analyze: 'scan-search',
  external: 'arrow-up-right',
  next: 'arrow-right',
  back: 'arrow-left',
  search: 'search',
  check: 'check',
  flag: 'flag',
  close: 'x',
  up: 'arrow-up',
  down: 'arrow-down',
  plus: 'plus',
  draft: 'pen-line',
  inbox: 'inbox',
  shield: 'shield-check',
  loading: 'loader-circle',
  copy: 'copy',
  done: 'circle-check-big',
  reset: 'rotate-ccw',
};

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node tools/gen-icons.mjs <lucide-static>/icons');
  process.exit(1);
}
const entries = Object.entries(ICONS).map(([name, lucide]) => {
  const svg = readFileSync(path.join(dir, `${lucide}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s*\/>/g, '/>')
    .trim();
  return ` ${name}:'${inner.replace(/'/g, "\\'")}', // ${lucide}`;
});

const out = `// GENERATED by tools/gen-icons.mjs from Lucide ${LUCIDE_VERSION} (ISC licence, https://lucide.dev). Do not edit.
// Drawn at 16 px in controls and 20 px in navigation, 1.75 px stroke, currentColor (docs/UNIFIED-UI.md section 6).
// Elements with data-icon="<name>" (and optional data-icon-size) are filled in when this script runs;
// scripts build markup with window.PacketRatIcons.svg(name, size).
'use strict';
(function(){
const paths={
${entries.join('\n')}
};
function svg(name,size){
 const body=paths[name];if(!body)return '';
 const s=Number(size)||16;
 return '<svg class="fl-icon" width="'+s+'" height="'+s+'" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">'+body+'</svg>';
}
function hydrate(root){(root||document).querySelectorAll('[data-icon]').forEach(el=>{el.innerHTML=svg(el.dataset.icon,el.dataset.iconSize)})}
window.PacketRatIcons={svg,hydrate,names:Object.keys(paths)};
hydrate(document);
})();
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'Web', 'icons.js');
writeFileSync(target, out);
console.log(`wrote ${entries.length} icons to ${target}`);
