// Generates Web/icons.js from Lucide's SVG sources, so PacketRat ships only the icons it uses and
// never loads anything from a CDN (docs/UNIFIED-UI.md section 6). Development-only; the output is
// committed and the target workstation needs no Node.js.
//   npm pack lucide-static@1.54.0 && tar -xzf lucide-static-1.54.0.tgz
//   node tools/gen-icons.mjs package/icons
// Re-run only when the icon list changes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Remove HTML comments by scanning, then repeat. One /<!--...-->/ replace turns
// "<!<!---->-->" into "<!-->", which still starts a comment. "<!-->" and "<!--->"
// are empty comments in HTML, so markup after them is kept. An unclosed "<!--"
// drops the rest of the string. Same helper fits the other fleet icon generators.
export function stripSvgComments(svg) {
  let previous;
  do {
    previous = svg;
    svg = stripSvgCommentsOnce(svg);
  } while (svg !== previous);
  return svg;
}

function stripSvgCommentsOnce(svg) {
  const out = [];
  for (let i = 0; i < svg.length; ) {
    if (svg.startsWith('<!--', i)) {
      if (svg[i + 4] === '>') {
        i += 5;
        continue;
      }
      if (svg[i + 4] === '-' && svg[i + 5] === '>') {
        i += 6;
        continue;
      }
      const end = svg.indexOf('-->', i + 4);
      if (end === -1) break;
      i = end + 3;
      continue;
    }
    out.push(svg[i]);
    i += 1;
  }
  return out.join('');
}

// JavaScript single-quoted literal. Escape "\" before "'": escaping only the quote
// turns "\'" into "\\'", and the quote is live again.
export function jsSingleQuoted(value) {
  return "'" + value.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

export function svgInner(svg) {
  return stripSvgComments(svg)
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s*\/>/g, '/>')
    .trim();
}

export function iconRecord(name, lucide, svg) {
  return ` ${name}:${jsSingleQuoted(svgInner(svg))}, // ${lucide}`;
}

