// Generates Web/icons.js from Lucide's SVG sources, so PacketRat ships only the icons it uses and
// never loads anything from a CDN (docs/UNIFIED-UI.md section 6). Development-only; the output is
// committed and the target workstation needs no Node.js.
//   npm pack lucide-static@1.54.0 && tar -xzf lucide-static-1.54.0.tgz
//   node tools/gen-icons.mjs package/icons
// Re-run only when the icon list changes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Shared fleet comment stripper. stripSvgComments stays exported as an alias.
function commentEnd(s, from) {
  for (let j = from; j < s.length - 2; j++) {
    if (s[j] !== '-' || s[j + 1] !== '-') continue;
    if (s[j + 2] === '>') return j + 3;
    if (s[j + 2] === '!' && s[j + 3] === '>') return j + 4;
  }
  return -1;
}
function stripOnce(s) {
  let out = '';
  let i = 0;
  while (i < s.length) {
    const start = s.indexOf('<!--', i);
    if (start < 0) return out + s.slice(i);
    out += s.slice(i, start);
    if (s[start + 4] === '>') { i = start + 5; continue; }
    if (s[start + 4] === '-' && s[start + 5] === '>') { i = start + 6; continue; }
    const end = commentEnd(s, start + 4);
    if (end < 0) return out;
    i = end;
  }
  return out;
}
export function stripHtmlComments(input) {
  let cur = String(input);
  let prev;
  do { prev = cur; cur = stripOnce(cur); } while (cur !== prev);
  return cur;
}
export { stripHtmlComments as stripSvgComments };

// JavaScript single-quoted literal. Escape "\" before "'": escaping only the quote
// turns "\'" into "\\'", and the quote is live again.
export function jsSingleQuoted(value) {
  return "'" + value.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
}

export function svgInner(svg) {
  return stripHtmlComments(svg)
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s*\/>/g, '/>')
    .trim();
}

export function iconRecord(name, lucide, svg) {
  return ` ${name}:${jsSingleQuoted(svgInner(svg))}, // ${lucide}`;
}

